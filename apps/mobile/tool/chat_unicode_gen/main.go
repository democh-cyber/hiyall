// Command chat_unicode_gen writes apps/mobile/lib/core/chat/chat_unicode_tables.dart: the Unicode
// tables the app's chat text rules need (Cf and Mn/Me ranges, canonical combining classes and
// decompositions for NFC), taken from the same Go packages as the API's text rules so both sides
// agree. Run from services/api (it needs that module's golang.org/x/text):
//
//	go run ../../apps/mobile/tool/chat_unicode_gen/main.go > ../../apps/mobile/lib/core/chat/chat_unicode_tables.dart
package main

import (
	"fmt"
	"os"
	"strings"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

func ranges(tab ...*unicode.RangeTable) [][2]rune {
	var out [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		in := false
		for _, t := range tab {
			if unicode.Is(t, r) {
				in = true
			}
		}
		if !in {
			continue
		}
		if n := len(out); n > 0 && out[n-1][1] == r-1 {
			out[n-1][1] = r
		} else {
			out = append(out, [2]rune{r, r})
		}
	}
	return out
}

func emit(b *strings.Builder, name, doc string, vals []int) {
	fmt.Fprintf(b, "%s\nconst %s = <int>[", doc, name)
	line := 0
	for i, v := range vals {
		s := fmt.Sprintf("%d", v)
		if i > 0 {
			b.WriteString(",")
			line++
		}
		if line+len(s) > 96 {
			b.WriteString("\n ")
			line = 0
		} else if i > 0 {
			b.WriteString(" ")
			line++
		}
		b.WriteString(s)
		line += len(s)
	}
	b.WriteString("];\n\n")
}

func flat(r [][2]rune) []int {
	var o []int
	for _, p := range r {
		o = append(o, int(p[0]), int(p[1]))
	}
	return o
}

func main() {
	var b strings.Builder
	b.WriteString("// dart format off\n// GENERATED by apps/mobile/tool/chat_unicode_gen from golang.org/x/text/unicode/norm and the\n// standard library's unicode tables, the same sources as the API's text rules\n// (services/api/internal/domain/text.go). Do not edit by hand. Pairs and triples are flat.\n\n")
	emit(&b, "unicodeCfRanges", "/// Format characters (Cf): inclusive [first, last] pairs.", flat(ranges(unicode.Cf)))
	emit(&b, "unicodeMarkRanges", "/// Nonspacing and enclosing marks (Mn, Me): inclusive [first, last] pairs.", flat(ranges(unicode.Mn, unicode.Me)))
	// ccc ranges
	var ccc []int
	var lo rune = -1
	var cur uint8
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		var c uint8
		if r <= unicode.MaxRune {
			c = norm.NFC.PropertiesString(string(r)).CCC()
		}
		if r > 0 && c != cur || r == unicode.MaxRune+1 {
			if cur != 0 {
				ccc = append(ccc, int(lo), int(r-1), int(cur))
			}
			lo = r
			cur = c
		} else if lo < 0 {
			lo = r
		}
	}
	emit(&b, "unicodeCccRanges", "/// Canonical combining classes that are not 0: [first, last, class] triples.", ccc)
	var dec, comp []int
	for r := rune(0x80); r <= unicode.MaxRune; r++ {
		if r >= 0xAC00 && r <= 0xD7A3 {
			continue
		}
		d := []rune(norm.NFD.String(string(r)))
		if len(d) == 1 && d[0] == r {
			continue
		}
		dec = append(dec, int(r), len(d))
		for _, x := range d {
			dec = append(dec, int(x))
		}
		// Primary composite: the last character of the full decomposition joins what came before.
		if len(d) >= 2 && norm.NFC.String(string(r)) == string(r) {
			a := []rune(norm.NFC.String(string(d[:len(d)-1])))
			if len(a) == 1 && norm.NFC.String(string([]rune{a[0], d[len(d)-1]})) == string(r) {
				comp = append(comp, int(a[0]), int(d[len(d)-1]), int(r))
			}
		}
	}
	emit(&b, "unicodeDecompositions", "/// Full canonical decompositions: [char, count, parts...] records.", dec)
	emit(&b, "unicodeCompositions", "/// Primary composites: [first, second, composite] triples.", comp)
	os.Stdout.WriteString(b.String())
}
